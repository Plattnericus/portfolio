"use client";

import { useEffect, useRef, useState } from "react";
import { AsciiTitle } from "@/lib/ascii/ascii-title";
import { family } from "@/lib/fonts";
import { getLenis } from "@/lib/motion";
import { SPECIMEN_EVENT, markSecret } from "@/lib/secrets";
import { worldState } from "@/lib/world/state";
import { site } from "@/lib/site";

const DEFAULT = "ABCDEFGHIJKLM NOPQRSTUVWXYZ 0123456789 &@!?";

/**
 * Hidden. Type the name anywhere and the site's own face shows itself: a
 * specimen you can type into, drawn in characters.
 */
export default function Specimen() {
  const [open, setOpen] = useState(false);
  const [text, setText] = useState(DEFAULT);
  const hostRef = useRef<HTMLDivElement>(null);
  const titleRef = useRef<AsciiTitle | null>(null);

  useEffect(() => {
    let typed = "";
    const onKey = (e: KeyboardEvent) => {
      const t = e.target as HTMLElement | null;
      if (e.metaKey || e.ctrlKey || e.altKey) return;
      if (t && (t.tagName === "INPUT" || t.tagName === "TEXTAREA")) return;
      if (e.key.length !== 1) return;
      typed = (typed + e.key.toLowerCase()).slice(-5);
      if (typed === "nexor") {
        // the last key would otherwise land in the specimen's input
        e.preventDefault();
        typed = "";
        setOpen(true);
      }
    };
    const onEvent = () => setOpen(true);
    window.addEventListener("keydown", onKey);
    window.addEventListener(SPECIMEN_EVENT, onEvent);
    return () => {
      window.removeEventListener("keydown", onKey);
      window.removeEventListener(SPECIMEN_EVENT, onEvent);
    };
  }, []);

  useEffect(() => {
    const host = hostRef.current;
    if (!open || !host) return;
    markSecret("specimen");
    getLenis()?.stop();
    worldState.covered++;
    const title = new AsciiTitle(host, {
      fontFamily: family("mono"),
      displayFamily: family("display"),
      maxCell: 9,
      label: false,
      reveal: "assemble",
      knockout: site.colors.bg,
    });
    titleRef.current = title;
    title.set(DEFAULT);
    const onKey = (e: KeyboardEvent) => {
      if (e.key === "Escape") setOpen(false);
    };
    window.addEventListener("keydown", onKey);
    return () => {
      window.removeEventListener("keydown", onKey);
      title.destroy();
      titleRef.current = null;
      worldState.covered = Math.max(0, worldState.covered - 1);
      getLenis()?.start();
    };
  }, [open]);

  if (!open) return null;

  return (
    <div className="sp" role="dialog" aria-modal="true" aria-label="Nexor Grid type specimen">
      <div className="sp-head">
        <p className="sp-name">Nexor Grid</p>
        <p className="muted">
          the face of this site. a 5 x 7 grid, every edge at 0, 45 or 90 degrees. 64 glyphs, 4 KB, generated by a
          script.
        </p>
      </div>
      <div ref={hostRef} className="sp-art" aria-hidden="true" />
      <div className="sp-foot">
        <label className="sp-type">
          <span className="sp-prompt">type:</span>
          <input
            value={text}
            maxLength={60}
            autoFocus
            spellCheck={false}
            autoComplete="off"
            onChange={(e) => {
              setText(e.target.value);
              titleRef.current?.set(e.target.value || " ", false);
            }}
          />
        </label>
        <button type="button" className="tl" onClick={() => setOpen(false)}>
          <span>close</span>
          <span className="arrow">esc</span>
        </button>
      </div>
    </div>
  );
}
